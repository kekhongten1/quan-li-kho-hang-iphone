package model;

public class ThongKeKho {
    private int tongSanPham;
    private int tongTonKho;
    private int sanPhamSapHet;
    private int tongDaNhap;
    private int tongDaXuat;
    private double giaTriTonKho;

    public int getTongSanPham() {
        return tongSanPham;
    }

    public void setTongSanPham(int tongSanPham) {
        this.tongSanPham = tongSanPham;
    }

    public int getTongTonKho() {
        return tongTonKho;
    }

    public void setTongTonKho(int tongTonKho) {
        this.tongTonKho = tongTonKho;
    }

    public int getSanPhamSapHet() {
        return sanPhamSapHet;
    }

    public void setSanPhamSapHet(int sanPhamSapHet) {
        this.sanPhamSapHet = sanPhamSapHet;
    }

    public int getTongDaNhap() {
        return tongDaNhap;
    }

    public void setTongDaNhap(int tongDaNhap) {
        this.tongDaNhap = tongDaNhap;
    }

    public int getTongDaXuat() {
        return tongDaXuat;
    }

    public void setTongDaXuat(int tongDaXuat) {
        this.tongDaXuat = tongDaXuat;
    }

    public double getGiaTriTonKho() {
        return giaTriTonKho;
    }

    public void setGiaTriTonKho(double giaTriTonKho) {
        this.giaTriTonKho = giaTriTonKho;
    }
}
